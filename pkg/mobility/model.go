package mobility

import (
	"encoding/json"
	"strings"
	"time"
)

// Waypoint represents a single GPS tracking point collected from mobile devices.
type Waypoint struct {
	Latitude        float64   `firestore:"latitude" json:"latitude"`
	Longitude       float64   `firestore:"longitude" json:"longitude"`
	Timestamp       time.Time `firestore:"timestamp" json:"timestamp"`
	DurationMinutes float64   `firestore:"duration_minutes" json:"duration_minutes"`
	IsStay          bool      `firestore:"is_stay" json:"is_stay"`
	Classification  string    `firestore:"classification" json:"classification"` // "indoor" or "outdoor"
	ZoneName        string    `firestore:"zone_name,omitempty" json:"zone_name,omitempty"`
	AQI             int       `firestore:"aqi,omitempty" json:"aqi,omitempty"`
	PM25            float64   `firestore:"pm2_5,omitempty" json:"pm2_5,omitempty"`
}

// UnmarshalJSON provides flexible decoding of waypoints from various client formats
// (e.g., lat vs latitude, lon vs longitude vs lng, string or RFC3339 timestamps).
func (w *Waypoint) UnmarshalJSON(data []byte) error {
	type rawWaypoint struct {
		Lat             *float64 `json:"lat"`
		Latitude        *float64 `json:"latitude"`
		Lon             *float64 `json:"lon"`
		Longitude       *float64 `json:"longitude"`
		Lng             *float64 `json:"lng"`
		TimestampStr    *string  `json:"timestamp"`
		DurationMinutes *float64 `json:"duration_minutes"`
		Duration        *float64 `json:"duration"`
		IsStay          *bool    `json:"is_stay"`
		Classification  string   `json:"classification"`
		ZoneName        string   `json:"zone_name"`
		AQI             int      `json:"aqi"`
		PM25            float64  `json:"pm2_5"`
	}

	var raw rawWaypoint
	if err := json.Unmarshal(data, &raw); err != nil {
		return err
	}

	if raw.Latitude != nil {
		w.Latitude = *raw.Latitude
	} else if raw.Lat != nil {
		w.Latitude = *raw.Lat
	}

	if raw.Longitude != nil {
		w.Longitude = *raw.Longitude
	} else if raw.Lon != nil {
		w.Longitude = *raw.Lon
	} else if raw.Lng != nil {
		w.Longitude = *raw.Lng
	}

	if raw.DurationMinutes != nil {
		w.DurationMinutes = *raw.DurationMinutes
	} else if raw.Duration != nil {
		w.DurationMinutes = *raw.Duration
	}

	if raw.IsStay != nil {
		w.IsStay = *raw.IsStay
	}

	if raw.TimestampStr != nil {
		tStr := strings.TrimSpace(*raw.TimestampStr)
		// Try parsing common datetime formats
		parsedTime, err := time.Parse(time.RFC3339, tStr)
		if err != nil {
			parsedTime, err = time.Parse("2006-01-02 15:04:05", tStr)
		}
		if err == nil {
			w.Timestamp = parsedTime
		} else {
			w.Timestamp = time.Now().UTC()
		}
	} else {
		w.Timestamp = time.Now().UTC()
	}

	w.Classification = raw.Classification
	w.ZoneName = raw.ZoneName
	w.AQI = raw.AQI
	w.PM25 = raw.PM25

	return nil
}

// BatchRequest represents the incoming payload from mobile app.
type BatchRequest struct {
	UserID    string     `json:"user_id,omitempty"`
	Date      string     `json:"date,omitempty"` // YYYY-MM-DD
	Waypoints []Waypoint `json:"waypoints"`
}

// ExposureStats aggregates indoor vs outdoor exposure metrics.
type ExposureStats struct {
	TotalIndoorMinutes  float64 `firestore:"total_indoor_minutes" json:"total_indoor_minutes"`
	TotalOutdoorMinutes float64 `firestore:"total_outdoor_minutes" json:"total_outdoor_minutes"`
	AverageOutdoorAQI   float64 `firestore:"average_outdoor_aqi" json:"average_outdoor_aqi"`
	AverageOutdoorPM25  float64 `firestore:"average_outdoor_pm25" json:"average_outdoor_pm25"`
	MaxAQI              int     `firestore:"max_aqi" json:"max_aqi"`
	WorstAreaName       string  `firestore:"worst_area_name" json:"worst_area_name"`
	WorstAreaAQI        int     `firestore:"worst_area_aqi" json:"worst_area_aqi"`
	WorstAreaTimestamp  string  `firestore:"worst_area_timestamp,omitempty" json:"worst_area_timestamp,omitempty"`
	WaypointsProcessed  int     `firestore:"waypoints_processed" json:"waypoints_processed"`
}

// AIDiagnosis holds doctor diagnosis and health impact evaluation generated by LLM.
type AIDiagnosis struct {
	ImpactScore     float64  `firestore:"impact_score" json:"impact_score"`         // 0 - 100
	RiskLevel       string   `firestore:"risk_level" json:"risk_level"`             // "Rendah", "Sedang", "Tinggi", "Berbahaya"
	Summary         string   `firestore:"summary" json:"summary"`                   // 1-2 kalimat ringkas
	DoctorDiagnosis string   `firestore:"doctor_diagnosis" json:"doctor_diagnosis"` // Analisis dokter paru
	Recommendations []string `firestore:"recommendations" json:"recommendations"`   // Langkah proteksi harian
}

// DailyAnalysis is the persisted record in Firestore representing a user's day.
type DailyAnalysis struct {
	ID        string        `firestore:"id" json:"id"` // {user_id}_{date}
	UserID    string        `firestore:"user_id" json:"user_id"`
	Date      string        `firestore:"date" json:"date"`
	Stats     ExposureStats `firestore:"stats" json:"stats"`
	Analysis  AIDiagnosis   `firestore:"analysis" json:"analysis"`
	Waypoints []Waypoint    `firestore:"waypoints,omitempty" json:"waypoints,omitempty"`
	CreatedAt time.Time     `firestore:"created_at" json:"created_at"`
	UpdatedAt time.Time     `firestore:"updated_at" json:"updated_at"`
}
